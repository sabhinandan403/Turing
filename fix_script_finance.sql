    PROCEDURE exec_dml(p_sql IN CLOB, p_desc IN VARCHAR2) IS
        v_rows NUMBER;
    BEGIN
        EXECUTE IMMEDIATE p_sql;
        v_rows := SQL%ROWCOUNT;
        COMMIT;
        DBMS_OUTPUT.PUT_LINE('✔ DATA LOADED: ' || p_desc || ' (' || v_rows || ' rows inserted)');
    EXCEPTION
        WHEN OTHERS THEN
            DBMS_OUTPUT.PUT_LINE('✖ ERROR loading data for ' || p_desc || ': ' || SQLERRM);
            ROLLBACK;
            RAISE;
    END exec_dml;


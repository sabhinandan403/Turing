    PROCEDURE exec_ddl(p_sql IN CLOB, p_desc IN VARCHAR2) IS
    BEGIN
        EXECUTE IMMEDIATE p_sql;
        DBMS_OUTPUT.PUT_LINE('✔ TABLE CREATED: ' || p_desc);
    EXCEPTION
        WHEN OTHERS THEN
            DBMS_OUTPUT.PUT_LINE('✖ ERROR creating table ' || p_desc || ': ' || SQLERRM);
            RAISE;
    END exec_ddl;

